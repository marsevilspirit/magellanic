/**
 * Main JavaScript file for the Hugo theme
 */
document.addEventListener("DOMContentLoaded", () => {
  console.log("This site was generated by Hugo.");
  
  // Home page animations
  if (document.querySelector('.home-page')) {
    initHomeAnimations();
  }
});

function initHomeAnimations() {
  // Animation elements and their delays (in milliseconds)
  const animationSequence = [
    { selector: '.avatar', delay: 100 },
    { selector: '.persona', delay: 200 },
    { selector: '.identity', delay: 400 },
    { selector: '.articles', delay: 600 },
    { selector: '.articles .section-title', delay: 700 },
    { selector: '.more', delay: 1600 }
  ];
  
  // Animate articles with staggered delays
  const articles = document.querySelectorAll('.article');
  
  // Start animations
  animationSequence.forEach(item => {
    setTimeout(() => {
      const element = document.querySelector(item.selector);
      if (element) {
        element.classList.add('animate');
      }
    }, item.delay);
  });
  
  // Animate articles with staggered delays
  articles.forEach((article, index) => {
    setTimeout(() => {
      article.classList.add('animate');
    }, 900 + (index * 100)); // Start at 900ms, then 100ms intervals
  });
}
